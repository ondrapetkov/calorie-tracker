/** Built-in tag ids for the given categories, unique, in the order their categories appear. */
export function suggestTagsFromCategories(categories: readonly string[]): string[] {
  const out = new Set<string>()
  for (const c of categories) {
    const tag = OFF_CATEGORY_TAGS[c]
    if (tag) out.add(tag)
  }
  return [...out]
}
